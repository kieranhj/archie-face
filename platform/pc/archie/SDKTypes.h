// ============================================================================
// PC stub: maps ArchieSDK integer types to stdint.h equivalents.
// This header shadows archie/SDKTypes.h from the ArchieSDK on PC builds.
// ============================================================================

#ifndef __SDKTYPES_H__
#define __SDKTYPES_H__

#include <stdint.h>

typedef uint8_t  u8;
typedef uint16_t u16;
typedef uint32_t u32;
typedef int8_t   s8;
typedef int16_t  s16;
typedef int32_t  s32;

#endif // __SDKTYPES_H__
